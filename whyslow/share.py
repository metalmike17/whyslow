"""Shareable, anonymized report: paste it into a forum post or bug report to get help.

Privacy model, in order of importance:
1. Nothing is ever sent anywhere. We only produce text; the user reads it and decides.
2. Personal details are removed *by pattern and by known values* (username, real name, hostname, home
   path, emails, UUIDs, MAC/IP addresses, drive labels, serial numbers).
3. Fail closed: after redaction the text is scanned again for the user's own identifiers; if any is
   still present the report is refused rather than emitted.
4. ``strict`` additionally hides the names of programs that are not well-known, since a program name can
   itself reveal something about its owner.
"""
from __future__ import annotations

import os
import platform
import pwd
import re
import socket
import time
from dataclasses import dataclass, field

from . import __version__

SECTIONS = ("system", "slowdowns", "crashes", "hardware", "boot", "battery")
HEADER = ("Generated by WhySlow. Personal details (username, hostname, paths, drive names, addresses) were "
          "removed automatically, but please skim it before posting.")

_UUID = re.compile(r"\b[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\b")
_UNIT_SUFFIX = ("service", "mount", "scope", "socket", "device", "timer", "slice", "target", "automount", "path", "swap")
_EMAIL = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)*\.(?!(?:" + "|".join(_UNIT_SUFFIX) + r")\b)[A-Za-z]{2,}\b")
_MAC = re.compile(r"\b(?:[0-9a-fA-F]{2}[:-]){5}[0-9a-fA-F]{2}\b")
_IPV4 = re.compile(r"\b(?!(?:127|0)\.)(?:\d{1,3}\.){3}\d{1,3}\b(?!\.\d)")
_IPV6 = re.compile(r"\b(?:[0-9a-fA-F]{1,4}:){3,7}[0-9a-fA-F]{1,4}\b")
_MOUNT = re.compile(r"(/run/media/[^/\s]+/|/media/[^/\s]+/|/mnt/)([^\s/`'\")\]]+)")
_SERIAL = re.compile(r"(?i)\b(serial(?:[_ ]?(?:number|no))?|SN)\s*[=:]\s*\S+")
_BYID = re.compile(r"/dev/disk/by-[\w-]+/\S+")
_HEXTOKEN = re.compile(r"\b[0-9A-F]{16}\b")          # NTFS volume serials etc.


@dataclass
class Redactor:
    user: str = ""
    realname: str = ""
    host: str = ""
    home: str = ""
    keep: set[str] = field(default_factory=set)        # app names safe to show in strict mode
    hide_apps: set[str] = field(default_factory=set)   # app names to mask in strict mode

    @classmethod
    def for_current_user(cls) -> "Redactor":
        pw = pwd.getpwuid(os.getuid())
        real = pw.pw_gecos.split(",")[0].strip()
        return cls(pw.pw_name, real, socket.gethostname(), os.path.expanduser("~"))

    def _names(self) -> list[str]:
        out = [n for n in (self.realname, self.user, self.host) if n and len(n) >= 2]
        return sorted(set(out), key=len, reverse=True)

    def apply(self, text: str) -> str:
        t = text
        # drive and mount names are often a person's label for their stuff: keep the structure, drop the name
        t = _MOUNT.sub(lambda m: m.group(1) + "<drive>", t)
        t = _BYID.sub("<disk-id>", t)
        t = _SERIAL.sub(lambda m: m.group(1) + ": <serial>", t)
        t = _EMAIL.sub("<email>", t)
        t = _UUID.sub("<uuid>", t)
        t = _MAC.sub("<mac>", t)
        t = _IPV6.sub("<ip>", t)
        t = _IPV4.sub("<ip>", t)
        t = _HEXTOKEN.sub("<id>", t)
        if self.home and self.home != "/":
            t = t.replace(self.home, "~")
        for n in self._names():
            if len(n) < 4:
                # very short names ("al", "me") would wreck ordinary words: only replace them in obvious spots
                t = re.sub(rf"(?<=[/@]){re.escape(n)}(?![\w-])", "user", t)
                t = re.sub(rf"\b{re.escape(n)}@", "user@", t)
            else:
                t = re.sub(rf"(?<![A-Za-z0-9]){re.escape(n)}(?![A-Za-z0-9])", "user" if n == self.user else
                           "host" if n == self.host else "name", t, flags=re.I)
        return self._mask_apps(t)

    def _mask_apps(self, t: str) -> str:
        names = sorted((a for a in self.hide_apps if a not in self.keep), key=len, reverse=True)
        for i, a in enumerate(names, 1):
            t = re.sub(rf"(?<![\w-]){re.escape(a)}(?![\w-])", f"app-{i}", t)
        return t

    def leaks(self, text: str) -> list[str]:
        """Own identifiers still present in the text (should always be empty after apply())."""
        found = []
        for n in self._names():
            if len(n) >= 4 and re.search(rf"(?<![A-Za-z0-9]){re.escape(n)}(?![A-Za-z0-9])", text, re.I):
                found.append("name" if n == self.realname else "username" if n == self.user else "hostname")
        if self.home and self.home != "/" and self.home in text:
            found.append("home path")
        return found


class LeakError(RuntimeError):
    pass


# --------------------------------------------------------------------------
# system facts (no identifiers: models and sizes only)
# --------------------------------------------------------------------------
def _read(path: str) -> str:
    try:
        with open(path) as f:
            return f.read()
    except OSError:
        return ""


def system_facts(snap=None) -> list[str]:
    """Hardware/software context a helper needs. Built from hwcheck's snapshot when given."""
    osr = dict(l.split("=", 1) for l in _read("/etc/os-release").splitlines() if "=" in l)
    cpu = next((l.split(":", 1)[1].strip() for l in _read("/proc/cpuinfo").splitlines() if l.startswith("model name")), "unknown CPU")
    mem = next((int(l.split()[1]) for l in _read("/proc/meminfo").splitlines() if l.startswith("MemTotal")), 0)
    lines = [f"OS: {osr.get('PRETTY_NAME', 'unknown').strip(chr(34))}",
             f"Kernel: {platform.release()}",
             f"Desktop: {os.environ.get('XDG_CURRENT_DESKTOP', '?')} ({os.environ.get('XDG_SESSION_TYPE', '?')})",
             f"CPU: {cpu}, {os.cpu_count()} threads",
             f"RAM: {mem / 1048576:.0f} GB"]
    gpu = _gpu_names()
    if gpu:
        lines.append("GPU: " + "; ".join(gpu))
    if snap is not None:
        kinds = [k for k in (disk_label(n, i, int(int(_read(f"/sys/block/{n}/size").strip() or 0) * 512 / 1e9))
                             for n, i in sorted(snap.disks.items())) if k]
        if kinds:
            lines.append("Disks: " + ", ".join(kinds))
        fss = sorted({m["fs"] or m["fstype"] for m in snap.mounts if m["fs"] or m["fstype"]})
        if fss:
            lines.append("Filesystems: " + ", ".join(fss))
        if snap.swaps:
            lines.append("Swap: " + ", ".join(sorted({w["kind"] for w in snap.swaps})))
    lines.append(f"WhySlow {__version__}")
    return lines


def disk_label(name: str, info: dict, size_gb: int) -> str | None:
    """'NVMe SSD 1024 GB' — kind and size only, never a model/serial. None for empty slots."""
    if size_gb == 0:
        return None                                 # empty card-reader slots
    # USB sticks often claim to be rotational, so the flag only means something for internal disks
    kind = ("NVMe SSD" if name.startswith("nvme") else "USB drive" if info["usb"]
            else "HDD" if info["rotational"] else "SATA SSD")
    return f"{kind} {size_gb} GB"


def apps_to_hide(apps, lookup) -> set[str]:
    """Strict mode: mask programs that are neither in the known-offenders DB nor generic helper names."""
    from .sampler import _GENERIC_COMM
    return {a for a in apps if not lookup(a) and a not in _GENERIC_COMM}


def _gpu_names() -> list[str]:
    import shutil, subprocess
    out = []
    try:
        if shutil.which("nvidia-smi"):
            r = subprocess.run(["nvidia-smi", "--query-gpu=name,driver_version", "--format=csv,noheader"],
                               capture_output=True, text=True, timeout=3).stdout.strip().splitlines()
            out += [x.replace(",", " driver") for x in r if x]
        if not out and shutil.which("lspci"):
            r = subprocess.run(["lspci"], capture_output=True, text=True, timeout=3).stdout.splitlines()
            out += [re.sub(r"^\S+\s+[^:]+:\s*", "", l) for l in r if re.search(r"VGA|3D controller", l)]
    except (OSError, subprocess.SubprocessError):
        pass
    return out


