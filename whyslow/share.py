# composition
# --------------------------------------------------------------------------
def _fence(body: str) -> str:
    return "```\n" + body.strip("\n") + "\n```"


def compose(parts: dict[str, str], redactor: Redactor, strict: bool = False, now: float | None = None) -> str:
    """Join the sections, anonymize, and verify nothing personal survived."""
    day = time.strftime("%Y-%m-%d", time.localtime(now or time.time()))
    titles = {"system": "System", "slowdowns": "Recent slowdowns", "crashes": "Crashes / unexpected shutdowns",
              "hardware": "Hardware check", "boot": "Boot time", "battery": "Battery"}
    out = [f"# WhySlow report ({day})", "", f"_{HEADER}_", ""]
    for key in SECTIONS:
        if parts.get(key):
            out += [f"## {titles[key]}", _fence(parts[key]), ""]
    text = "\n".join(out)
    text = redactor.apply(text)
    bad = redactor.leaks(text)
    if bad:
        raise LeakError("refusing to produce the report: personal details survived redaction (" + ", ".join(bad) + ")")
    return text


def gather(sections: set[str] | None = None, samples: list[dict] | None = None) -> tuple[dict[str, str], set[str]]:
    """Run the real collectors. Returns (section texts, app names seen in them)."""
    from . import analyze as an, battery, blackbox, boot, hwcheck, offenders
    want = sections or set(SECTIONS)
    parts: dict[str, str] = {}
    apps: set[str] = set()
    snap = None
    if want & {"system", "hardware"}:
        snap = hwcheck.collect()
    if "system" in want:
        parts["system"] = "\n".join(system_facts(snap))
    if "hardware" in want:
        parts["hardware"] = hwcheck.render(*hwcheck.run_checks(snap))
    if samples is None:
        from .cli import KEEP_SECONDS, load_log
        samples = load_log(KEEP_SECONDS)
    if "slowdowns" in want and len(samples) > 1:
        eps = an.analyze(samples)[:3]
        parts["slowdowns"] = an.render(eps, samples, limit=3)
        for e in eps:
            apps.update(c.app for c in e.culprits)
            apps.update(v.app for v in getattr(e, "victims", []))
    if "crashes" in want:
        incs = blackbox.list_incidents()[:3]
        if incs:
            parts["crashes"] = "\n\n".join("\n".join(blackbox.describe_incident(i)) for i in incs)
    if "boot" in want:
        parts["boot"] = boot.render(boot.run_analysis())
    if "battery" in want:
        rep = battery.analyze(samples, battery.info(), battery.context(), offenders.lookup)
        if rep.status == "ok":
            parts["battery"] = battery.render(rep)
            apps.update(c.app for c in rep.culprits)
    return parts, apps


def build(sections: set[str] | None = None, strict: bool = False, samples: list[dict] | None = None) -> str:
    from . import offenders
    parts, apps = gather(sections, samples)
    red = Redactor.for_current_user()
    if strict:
        red.hide_apps = apps_to_hide(apps, offenders.lookup)
    return compose(parts, red, strict)
